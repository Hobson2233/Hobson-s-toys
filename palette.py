"""palette.py —— 界面与站点**共用的唯一调色板**（2026-10-05 抽出）。

为什么单独一个模块：

    `campus_login.py` 里原本躺着 19 个界面颜色常量，而 `make_site.py` 的
    站点 CSS 里另有一份 44 个颜色的字面量 —— 实测**两边手工重合 15 个**。
    站点的 CSS 注释自己都写着「配色跟着程序界面走」，但没有任何机制保证，
    改一次配色要记得改两处，而「记得」这种东西迟早会漏。

    现在程序侧 `from palette import ...`，站点侧 `import palette` 之后
    生成 CSS 变量（`make_site.py` 的 `palette_css()`），源头只剩这一个文件。

🔴 2026-10-17：**整套换成 Windows 11 Fluent 的值**（用户从四个方案里挑的 A）。
    换之前是「slate 冷灰 + #2563eb 蓝」，那是 Tailwind 那一路的网页配色；
    Fluent 的关键差别有三条，缺一条都不像 Win11：

      ① 底色是**中性灰**而不是冷灰（`#f3f3f3` vs `#eef1f6`）——
         冷灰带蓝调，一眼就是网页；Win11 的 Mica 底色是中性的。
      ② 主色是**系统强调色蓝** `#0067c0`，比 Tailwind 的 `#2563eb` 更偏青、
         更暗一档。Win11 上几乎所有的蓝都是这个值。
      ③ 灰阶不再是「蓝灰系」（原来的 SUB `#64748b` 带明显蓝调），
         而是纯中性灰（`#5c5c5c`）—— 这是最容易露馅的一处。

⚠️ 改这里 = 同时改软件和网站的外观。改完记得跑：
    · `python make_site.py`            —— 站点 CSS 是构建时生成的
    · `python refresh_screenshot.py`   —— 首页截图会过期
    · `ui_contrast_test.py`            —— 按钮底色不能和它坐的背景同色
"""

# ---------------------------------------------------------------- 中性色（Win11 中性灰）
# 2026-10-17 换成 Fluent 的一套。原来 `#eef1f6 + #2563eb` 是网页观感：
# 底色带蓝、字色带蓝、连次要文字都是 slate 蓝灰，一屏看下来"很网页"。
# Fluent 的中性色是**真中性**（R=G=B 或几乎相等），只有主色带彩度。
BG = "#f3f3f3"          # 窗口 / 页面底色（Win11 浅色 Mica 的等效值）
CARD = "#ffffff"        # 卡片 / 输入框底色
FG = "#1a1a1a"          # 主文字（Win11 正文接近纯黑，不是深蓝黑）
SUB = "#5c5c5c"         # 次要文字 / 分区标题
LINE = "#e5e5e5"        # 卡片描边 / 分隔线
FIELD = "#fbfbfb"       # 输入框内底色
# 分区标题的文字色。
# 🔴 2026-10-17（换 Fluent）起**直接等于正文色** —— Win11 的分区标题靠
#    「加粗 + 和正文同号」拉开层次，**不靠换颜色**。原来那个 `#2b2b2b`
#    是「比正文浅一点点的灰」，配上小一号的字，结果标题压不住正文。
#    仍留一个独立名字：将来要单独调标题色时只改这里，不用动全界面的 FG。
# ⚠️ 写成 `= FG` 而不是抄一遍字面量 —— 抄一遍就是一处漂移源（红线 58）。
SEC_FG = FG

# ---------------------------------------------------------------- 导航栏（2026-10-17 新增）
# 🔴 Win11 的导航窗格**不是一张白卡片** —— 它和窗口同色（Mica），靠
#    「选中项的白底 + 左侧强调条」来指示当前位置。
#    原来这里是一张 `round_panel(fill=CARD)` 的白卡，那是「卡片式侧栏」，
#    属于网页后台的观感，不是 Win11。
#    ⚠️ 现在导航栏底色比内容区**深一档**（`#ebebeb` vs `#f3f3f3`），
#       这样未选中的项就算透明也看得出这一竖条是个独立区域。
NAV_BG = "#ebebeb"      # 导航窗格底色
NAV_HOVER = "#e0e0e0"   # 导航项悬停（落在 NAV_BG 上，差 11 级）
NAV_ACTIVE = "#ffffff"  # 导航项选中：白底
NAV_BAR = "#0067c0"     # 选中项左侧那条强调竖条（和 BLUE 同值，语义不同所以分开命名）

# ---------------------------------------------------------------- 主色
BLUE = "#0067c0"        # 主色（Win11 系统强调色）
BLUE_DARK = "#005fb8"   # 主色悬停
BLUE_SOFT = "#e8f0fb"   # 主色的浅底（标签、可点小字）
BLUE_HOVER = "#d6e6fa"  # 浅底的悬停
BLUE_ACTIVE = "#004578" # 主色按下态

# ---------------------------------------------------------------- 语义色
OK = "#107c10"          # Win11 的成功绿（比 #16a34a 更暗更黄）
OK_SOFT = "#e6f4e6"
DANGER = "#c42b1c"      # Win11 的错误红
DANGER_SOFT = "#fdecec"
DANGER_HOVER = "#f8d7d4"
DANGER_ACTIVE = "#f3c4c0"
WARN = "#8a5300"
# 2026-10-12 加：账号行上「这个账号属于别的学校」那个小标签的底色。
# ⚠️ 白卡上的浅底必须过 `_CONTRAST_MIN`（8）：这个值对 CARD 的最大单通道差是 28。
WARN_SOFT = "#fdf3e3"

# ---------------------------------------------------------------- 次要控件（2026-10-17 新增）
# Win11 的「默认按钮」是**浅灰底 + 细描边**，不是白底 + 描边 ——
# 白底按钮落在白卡上会过不了 `ui_contrast_check`（差 0 级 = 按钮隐形），
# 而那正是这套自检存在的理由。所以取「浅一档的灰」而不是白。
BTN_SOFT = "#f5f5f5"    # 次要按钮静止态（落在白卡上差 10 级）
# ⚠️ 落在**页面灰底**（BG #f3f3f3）上的次要按钮不能复用上面那个 ——
#    #f5f5f5 和 BG 只差 2 级，`ui_contrast_check` 会（正确地）判成「按钮隐形」。
#    所以要单独一档更深的。
BTN_SOFT_ON_BG = "#e9e9e9"   # 落在 BG 上（差 10 级）
BTN_HOVER = "#ebebeb"
BTN_ACTIVE = "#e0e0e0"
BTN_PRESS = "#d6d6d6"   # 按下态再深一档
BTN_FG = "#1a1a1a"      # 次要按钮的文字
CHECK_EDGE = "#9a9a9a"  # 复选框未选中时的描边
NEUTRAL_SOFT = "#e9e9e9"  # 中性浅底（「不在校园网 / 状态未知」的徽章底）
MUTED = "#8a8a8a"       # 弱化文字 / 禁用文字 / 「状态未知」的灰
BLUE_PRESS = "#c3daf5"  # 主色浅底的按下态

# 浅底上的**深色文字**。浅底配深字才读得清（配主色本身对比度不够）。
OK_FG = "#0e5c0e"
DANGER_FG = "#8e1a10"
BLUE_FG = "#003a6b"

# 柱状图（本机流量历史）用的两个颜色。
CHART_AVG = "#c3daf5"   # 「日均」那条虚线
CHART_ZERO = "#d0d0d0"  # 「这天确实是 0」的那一小段（和「没有柱子」区分开）

# ---------------------------------------------------------------- 分区强调色（已停用）
# 2026-10-04 加：原来五个分区标题**全是同一种灰字**，一屏看下去没有任何层次，
# 也就是用户说的「太单调」。于是每个分区配一组「强色 + 浅底」，
# 浅底画圆角小徽章、强色画图标和描边。
#
# 🔴 2026-10-10（UI 方案 C）：**这个解法被推翻了，四组色全部删除**。
#    原因是「每个分区一个颜色」换来的不是层次，而是「花」——
#    五六个颜色一样亮、一样大，一屏之内像在展示调色板，
#    而那正是最容易被认成「AI 生成」的观感。
#    现在软件侧的分区徽章统一用 BLUE / BLUE_SOFT
#    （见 campus_login.py 的 SEC_STYLE），站点侧统一用 --t-blue-*；
#    层次改由**图标形状**和留白提供 —— 这件事不再需要颜色。
#
#    ⚠️ 以后想「给某个分区加个颜色」，先问一句：它是**真的语义色**吗
#       （像 OK / DANGER 那样表示状态）？只是「想让它和别的不一样」不算。
