# 一屏之内全是直角和纯色块。现在用中性偏冷的灰阶打底。
BG = "#eef1f6"          # 页面底色（卡片之间的缝）
CARD = "#ffffff"        # 卡片 / 输入框底色
FG = "#0f172a"          # 主文字
SUB = "#64748b"         # 次要文字 / 分区标题
LINE = "#e3e8ef"        # 卡片描边 / 分隔线
FIELD = "#f8fafc"       # 输入框内底色
# 分区标题的文字色。比 SUB 深一档 —— 标题要压得住下面的正文，
# 但又不抢主按钮的蓝。
SEC_FG = "#334155"

# ---------------------------------------------------------------- 主色
BLUE = "#2563eb"        # 主色
BLUE_DARK = "#1d4ed8"   # 主色按下态
BLUE_SOFT = "#e8efff"   # 主色的浅底（标签、可点小字）

# ---------------------------------------------------------------- 语义色
OK = "#16a34a"
OK_SOFT = "#e7f7ec"
DANGER = "#dc2626"
DANGER_SOFT = "#fdecec"
WARN = "#b45309"

# ---------------------------------------------------------------- 分区强调色（已停用）
# 2026-10-04 加：原来五个分区标题**全是同一种灰字**，一屏看下去没有任何层次，
# 也就是用户说的「太单调」。于是每个分区配一组「强色 + 浅底」，
# 浅底画圆角小徽章、强色画图标和描边。
#
# 🔴 2026-10-11（UI 方案 C）：**这个解法被推翻了，四组色全部删除**。
#    原因是「每个分区一个颜色」换来的不是层次，而是「花」——
#    五六个颜色一样亮、一样大，一屏之内像在展示调色板，
#    而那正是最容易被认成「AI 生成」的观感。
#    现在软件侧的分区徽章统一用 BLUE / BLUE_SOFT
#    （见 campus_login.py 的 SEC_STYLE），站点侧统一用 --t-blue-*；
#    层次改由**图标形状**和留白提供 —— 这件事不再需要颜色。
#
#    ⚠️ 以后想「给某个分区加个颜色」，先问一句：它是**真的语义色**吗
#       （像 OK / DANGER 那样表示状态）？只是「想让它和别的不一样」不算。
